/* ============================================================
   REYTER — чи є куди повертатись
   ------------------------------------------------------------
   Картка товару закривається поверненням назад — так покупець
   опиняється в каталозі там само, звідки пішов. Але якщо він
   прийшов за прямим посиланням (пошук, месенджер), «назад»
   винесло б його з сайту зовсім.

   Рахувати зміни адреси не можна: перехід між кольорами теж
   міняє адресу, але навмисне заміщає крок, а не додає — інакше
   «закрити» відмотувало б кольори по одному. Тому дивимось на
   довжину історії: вона росте лише від справжніх переходів.
   ============================================================ */

let base = -1;

/** Викликає оболонка магазину; має значення лише перший виклик —
 *  саме тоді ми запамʼятовуємо, з чого починали. */
export function noteNavigation(): void {
  if (base < 0) base = window.history.length;
}

/** Правда, якщо в цій вкладці вже була наша попередня сторінка. */
export function canGoBack(): boolean {
  return base >= 0 && window.history.length > base;
}
