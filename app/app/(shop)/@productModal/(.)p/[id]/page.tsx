import ProductModal from '@/components/ProductModal';
import ProductView, { productParams } from '@/views/ProductView';

/* ============================================================
   Картка товару поверх каталогу
   ------------------------------------------------------------
   Перехоплений маршрут: коли на адресу товару переходять із
   каталогу, сюди приїжджає ЛИШЕ картка, а сам каталог лишається
   змонтованим. Це не про красу — це про три речі одразу:

   • відповідь важить кілька кілобайтів замість ста тридцяти:
     каталог удруге не малюється;
   • закриття не перемальовує сторінку, тож фото й тексти не
     блимають;
   • прокрутка каталогу лишається такою, якою була.

   Пряме посилання на товар (з пошуку, з месенджера) сюди не
   потрапляє — його обслуговує звичайна сторінка /p/[id], і там
   картка малюється поверх каталогу вже на сервері.
   ============================================================ */

export const revalidate = 60;
export const generateStaticParams = productParams;

export default async function ProductModalPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  return <ProductModal lang="uk"><ProductView id={id} lang="uk" modal /></ProductModal>;
}
