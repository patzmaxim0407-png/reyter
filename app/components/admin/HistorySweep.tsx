'use client';

import { useEffect, useRef } from 'react';
import { db, watchAuth } from '@/lib/firebase';
import { sweepPending } from '@/lib/admin/loyalty-db';

/* ============================================================
   Зарахування минулих замовлень — саме собою
   ------------------------------------------------------------
   Стоїть в оболонці адмінки, а не на екрані програми, і це
   головне в ньому. Доти зарахування чекало, поки власник
   відкриє саме вкладку «Бали», — а він туди й не заходить
   тижнями. Учасник тим часом бачив нуль і мав рацію.

   Тепер прохід відбувається там, де власник буває щодня:
   відкрив замовлення чи склад — черга розібралась. Кнопки
   немає, і бути не має.

   ЩО ЦЕ КОШТУЄ. Один короткий запит на відкриття адмінки:
   «хто чекає». Майже завжди відповідь порожня, і на цьому все
   закінчується. Читання замовлень трапляється лише тоді, коли
   черга справді є.

   Мовчить навмисно. Це господарська робота, а не подія: якби
   на кожному відкритті адмінки вискакувала підказка про чужі
   бали, її б перестали читати за день. Слід лишається там, де
   йому місце, — у журналі нарахувань і в рядку учасника.
   ============================================================ */

/** Не частіше ніж раз на годину.
 *
 *  Адмінку відкривають і перезавантажують десятки разів на день,
 *  а вступ у програму — подія рідка. Прохід на кожному
 *  завантаженні означав би сотні зайвих читань бази щодня, і в
 *  найгірший день вони з'їли б денну норму — а разом із нею впав
 *  би й магазин для покупців, бо норма в них спільна.
 *
 *  Година — це затримка, якої ніхто не помітить: учасник однаково
 *  чекає на свої бали не секунди. */
const EVERY = 60 * 60 * 1000;
const MARK = 'reyter:sweep';

function due(): boolean {
  try {
    const was = Number(localStorage.getItem(MARK) || 0);
    if (Date.now() - was < EVERY) return false;
    localStorage.setItem(MARK, String(Date.now()));
    return true;
  } catch {
    // приватне вікно без сховища — краще пройти, ніж не пройти
    return true;
  }
}

export default function HistorySweep() {
  const ran = useRef(false);

  useEffect(() => {
    /* Ходимо один раз за відкриття вкладки. Черга не поповнюється
       щохвилини: вступ — рідка подія, а той, хто вступив після
       цього проходу, дочекається наступного відкриття. */
    const off = watchAuth((user) => {
      if (!user?.email || ran.current) return;
      ran.current = true;
      if (!due()) return;

      const d = db();
      if (!d) return;

      void sweepPending(d, user.email).catch(() => {
        /* Тиша тут навмисна: прав могло не вистачити, мережа
           могла впасти. Прапорці лишились, черга нікуди не
           поділась, спробуємо наступного разу. */
      });
    });
    return off;
  }, []);

  return null;
}
