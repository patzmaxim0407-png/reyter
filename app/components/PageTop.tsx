'use client';

import { useEffect } from 'react';

/* ============================================================
   Сторінка відкривається згори
   ------------------------------------------------------------
   Кабінет, оформлення й відстеження приїжджають майже порожніми:
   поки не відповіли Firebase чи Нова Пошта, у них лише рядок
   «завантажуємо». У цю мить сторінка коротша за екран, і браузер,
   переходячи з довгого каталогу, просто обрізає позицію
   прокрутки — а коли вміст нарешті приїде, притримує її при собі.
   Людина бачить сторінку з середини.

   Тому піднімаємо самі: на вході й ще раз, коли вміст зʼявився.
   Саме 'instant', а не 'auto': 'auto' означає «як каже CSS», а в
   нас там scroll-behavior: smooth — і сторінка повзла б угору
   чверть секунди на очах у людини.
   ============================================================ */

export default function PageTop({ ready = true }: { ready?: boolean }) {
  useEffect(() => {
    window.scrollTo({ top: 0, behavior: 'instant' });
  }, [ready]);

  return null;
}
